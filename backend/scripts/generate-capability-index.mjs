import fs from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const modulesDir = path.join(root, 'src', 'capabilities', 'modules');
const outputPath = path.join(root, 'src', 'capabilities', 'generated.ts');
const files = fs.readdirSync(modulesDir).filter((name) => name.endsWith('.ts')).sort();
const symbols = files.map((name) => {
  const source = fs.readFileSync(path.join(modulesDir, name), 'utf8');
  const match = source.match(/export const\s+(\w+Capability)\s*:/);
  if (!match) throw new Error(`${name} must export one *Capability descriptor`);
  return { file: name.slice(0, -3), symbol: match[1] };
});
const body = `// Generated by scripts/generate-capability-index.mjs. Do not hand-edit.\n${symbols.map((x) => `import { ${x.symbol} } from './modules/${x.file}.js';`).join('\n')}\n\nexport const generatedCapabilities = [\n${symbols.map((x) => `  ${x.symbol},`).join('\n')}\n] as const;\n`;
if (process.argv.includes('--check')) {
  if (!fs.existsSync(outputPath) || fs.readFileSync(outputPath, 'utf8') !== body) {
    console.error('Capability index is stale. Run npm run capabilities:generate in backend.');
    process.exit(1);
  }
} else {
  fs.writeFileSync(outputPath, body);
}
