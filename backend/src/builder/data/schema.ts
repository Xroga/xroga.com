import type { BuildSpec } from '../types.js';

/**
 * Customer database schema generation.
 *
 * Schemas are deterministic archetypes, not model output: the SQL a customer's database receives is
 * reviewable source with row-level security, least-privilege grants, constraints and indexes, and the
 * same input always produces the same bytes. A model never writes the migration that is applied.
 * The schema belongs to the customer's own Supabase project; Xroga's platform database is never a target.
 */

export type SchemaArchetypeId = 'tasks' | 'booking' | 'items';

export interface GeneratedSchema {
  readonly archetype: SchemaArchetypeId;
  readonly fileName: string;
  readonly sql: string;
  readonly tables: readonly string[];
  /** Human summary of what protects the data, shown with the approval. */
  readonly protections: readonly string[];
}

/** Fixed so the file name, and therefore the committed migration identity, is deterministic. */
export const MIGRATION_VERSION = '20260101000000';

/** Written as a table comment so a later run can tell "created by this Xroga schema" from "already there". */
export const schemaMarker = (archetype: SchemaArchetypeId): string => `xroga:schema:${archetype}:v1`;

const markTables = (archetype: SchemaArchetypeId, tables: readonly string[]) => tables.map((table) => `comment on table public.${table} is '${schemaMarker(archetype)}';`).join('\n');

const updatedAtTrigger = (table: string) => `
drop trigger if exists ${table}_set_updated_at on public.${table};
create trigger ${table}_set_updated_at before update on public.${table}
  for each row execute function public.xroga_set_updated_at();`;

const HEADER = `-- Generated by Xroga from your app requirements. Review before applying.
-- Owner: your Supabase project. Every table has row-level security enabled.
-- Idempotent: safe to run again.

create or replace function public.xroga_set_updated_at() returns trigger
language plpgsql set search_path = '' as $$
begin new.updated_at = now(); return new; end $$;
`;

const TASKS = `${HEADER}
create table if not exists public.tasks (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  title text not null check (char_length(title) between 1 and 200),
  description text check (description is null or char_length(description) <= 4000),
  status text not null default 'todo' check (status in ('todo', 'in_progress', 'done')),
  due_date date,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists tasks_owner_created_idx on public.tasks (owner_id, created_at desc);
${updatedAtTrigger('tasks')}

alter table public.tasks enable row level security;
revoke all on table public.tasks from anon, public;
${markTables('tasks', ['tasks'])}
grant select, insert, update, delete on table public.tasks to authenticated;

drop policy if exists tasks_select_own on public.tasks;
create policy tasks_select_own on public.tasks for select to authenticated using (owner_id = (select auth.uid()));
drop policy if exists tasks_insert_own on public.tasks;
create policy tasks_insert_own on public.tasks for insert to authenticated with check (owner_id = (select auth.uid()));
drop policy if exists tasks_update_own on public.tasks;
create policy tasks_update_own on public.tasks for update to authenticated using (owner_id = (select auth.uid())) with check (owner_id = (select auth.uid()));
drop policy if exists tasks_delete_own on public.tasks;
create policy tasks_delete_own on public.tasks for delete to authenticated using (owner_id = (select auth.uid()));
`;

const ITEMS = `${HEADER}
create table if not exists public.items (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  name text not null check (char_length(name) between 1 and 200),
  notes text check (notes is null or char_length(notes) <= 4000),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists items_owner_created_idx on public.items (owner_id, created_at desc);
${updatedAtTrigger('items')}

alter table public.items enable row level security;
revoke all on table public.items from anon, public;
${markTables('items', ['items'])}
grant select, insert, update, delete on table public.items to authenticated;

drop policy if exists items_select_own on public.items;
create policy items_select_own on public.items for select to authenticated using (owner_id = (select auth.uid()));
drop policy if exists items_insert_own on public.items;
create policy items_insert_own on public.items for insert to authenticated with check (owner_id = (select auth.uid()));
drop policy if exists items_update_own on public.items;
create policy items_update_own on public.items for update to authenticated using (owner_id = (select auth.uid())) with check (owner_id = (select auth.uid()));
drop policy if exists items_delete_own on public.items;
create policy items_delete_own on public.items for delete to authenticated using (owner_id = (select auth.uid()));
`;

const BOOKING = `${HEADER}
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  role text not null default 'customer' check (role in ('customer', 'admin')),
  created_at timestamptz not null default now()
);
-- The exported project may also carry the starter's own profiles table (without a role): add the column so this schema still applies.
alter table public.profiles add column if not exists role text not null default 'customer';

-- Role checks run as the table owner with an empty search path, so a user cannot read or forge them.
create or replace function public.xroga_is_admin() returns boolean
language sql stable security definer set search_path = '' as $$
  select exists (select 1 from public.profiles p where p.id = (select auth.uid()) and p.role = 'admin')
$$;
revoke all on function public.xroga_is_admin() from public, anon;
grant execute on function public.xroga_is_admin() to authenticated;

create table if not exists public.services (
  id uuid primary key default gen_random_uuid(),
  name text not null check (char_length(name) between 1 and 200),
  duration_minutes integer not null check (duration_minutes between 5 and 1440),
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.slots (
  id uuid primary key default gen_random_uuid(),
  service_id uuid not null references public.services(id) on delete cascade,
  starts_at timestamptz not null,
  ends_at timestamptz not null,
  created_at timestamptz not null default now(),
  check (ends_at > starts_at),
  unique (service_id, starts_at)
);
create index if not exists slots_service_start_idx on public.slots (service_id, starts_at);

create table if not exists public.bookings (
  id uuid primary key default gen_random_uuid(),
  slot_id uuid not null references public.slots(id) on delete cascade,
  customer_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  status text not null default 'confirmed' check (status in ('confirmed', 'cancelled')),
  created_at timestamptz not null default now()
);
-- The database itself, not the app, refuses a second confirmed booking for the same slot.
create unique index if not exists bookings_one_confirmed_per_slot on public.bookings (slot_id) where status = 'confirmed';
create index if not exists bookings_customer_idx on public.bookings (customer_id, created_at desc);

alter table public.profiles enable row level security;
alter table public.services enable row level security;
alter table public.slots enable row level security;
alter table public.bookings enable row level security;

revoke all on table public.profiles, public.services, public.slots, public.bookings from anon, public;
${markTables('booking', ['profiles', 'services', 'slots', 'bookings'])}
grant select on table public.profiles to authenticated;
grant select on table public.services, public.slots to authenticated;
grant insert, update, delete on table public.services, public.slots to authenticated;
grant select, insert on table public.bookings to authenticated;
-- Only the status of a booking can change after it is made (cancel); its slot and owner cannot.
grant update (status) on table public.bookings to authenticated;

drop policy if exists profiles_select_own on public.profiles;
create policy profiles_select_own on public.profiles for select to authenticated using (id = (select auth.uid()) or public.xroga_is_admin());

drop policy if exists services_read on public.services;
create policy services_read on public.services for select to authenticated using (active or public.xroga_is_admin());
drop policy if exists services_admin_write on public.services;
create policy services_admin_write on public.services for all to authenticated using (public.xroga_is_admin()) with check (public.xroga_is_admin());

drop policy if exists slots_read on public.slots;
create policy slots_read on public.slots for select to authenticated using (true);
drop policy if exists slots_admin_write on public.slots;
create policy slots_admin_write on public.slots for all to authenticated using (public.xroga_is_admin()) with check (public.xroga_is_admin());

drop policy if exists bookings_select on public.bookings;
create policy bookings_select on public.bookings for select to authenticated using (customer_id = (select auth.uid()) or public.xroga_is_admin());
drop policy if exists bookings_insert_own on public.bookings;
create policy bookings_insert_own on public.bookings for insert to authenticated with check (customer_id = (select auth.uid()));
drop policy if exists bookings_update on public.bookings;
create policy bookings_update on public.bookings for update to authenticated using (customer_id = (select auth.uid()) or public.xroga_is_admin()) with check (customer_id = (select auth.uid()) or public.xroga_is_admin());
`;

const BOOKING_RE = /\b(book(?:ing|ings)?|reserv(?:e|ation|ations)|appointment|appointments|slot|slots|schedul(?:e|ing))\b/i;
const TASKS_RE = /\b(task|tasks|to-?do|todo|kanban|checklist)\b/i;

export function chooseSchemaArchetype(spec: BuildSpec): SchemaArchetypeId | null {
  if (!spec.technicalRequirements.requiresDatabase) return null;
  const text = JSON.stringify([spec.objective, spec.title, spec.workflows, spec.acceptanceCriteria]);
  if (BOOKING_RE.test(text)) return 'booking';
  if (TASKS_RE.test(text)) return 'tasks';
  return 'items';
}

export function generateSchema(archetype: SchemaArchetypeId): GeneratedSchema {
  const common = ['Row-level security is enabled on every table.', 'Signed-out visitors have no access to any table.', 'Every column that holds a person\'s data is tied to the signed-in user by the database, not by the app.'];
  switch (archetype) {
    case 'tasks':
      return { archetype, fileName: `${MIGRATION_VERSION}_xroga_tasks.sql`, sql: TASKS, tables: ['tasks'], protections: [...common, 'A user can read and change only their own tasks.'] };
    case 'items':
      return { archetype, fileName: `${MIGRATION_VERSION}_xroga_items.sql`, sql: ITEMS, tables: ['items'], protections: [...common, 'A user can read and change only their own records.'] };
    case 'booking':
      return {
        archetype, fileName: `${MIGRATION_VERSION}_xroga_booking.sql`, sql: BOOKING, tables: ['profiles', 'services', 'slots', 'bookings'],
        protections: [...common, 'Customers see only their own bookings; staff (admin role) see all.', 'The database refuses two confirmed bookings for the same slot.', 'Only staff can create or change services and slots; roles cannot be changed from the app.'],
      };
  }
}

export function schemaFor(spec: BuildSpec): GeneratedSchema | null {
  const id = chooseSchemaArchetype(spec);
  return id ? generateSchema(id) : null;
}

/**
 * The files that make a database-backed project complete when it leaves Xroga (ZIP and GitHub): the exact reviewed
 * migration, version-controlled with the source, and a safe `.env.example` that names only the PUBLIC variables.
 * Anything the project already contains at those paths is left alone. Nothing here holds a value or a secret.
 */
export function databaseArtifacts(spec: BuildSpec, existing: ReadonlyArray<{ readonly path: string }>): Array<{ path: string; content: string }> {
  const schema = schemaFor(spec);
  if (!schema) return [];
  const have = new Set(existing.map((file) => file.path));
  const out: Array<{ path: string; content: string }> = [];
  const migration = `supabase/migrations/${schema.fileName}`;
  if (!have.has(migration)) out.push({ path: migration, content: schema.sql });
  if (!have.has('.env.example')) {
    out.push({
      path: '.env.example',
      content: [
        '# Public values only. Find both in your Supabase project under Project Settings, then API.',
        'NEXT_PUBLIC_SUPABASE_URL=',
        'NEXT_PUBLIC_SUPABASE_ANON_KEY=',
        '',
        '# Never put a service-role or secret key in this file, in source code, or in a NEXT_PUBLIC_ variable.',
        '',
      ].join('\n'),
    });
  }
  return out;
}
