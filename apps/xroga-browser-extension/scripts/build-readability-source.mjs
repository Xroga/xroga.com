// Wraps the vendored Mozilla Readability (Apache-2.0) as a string the read tool runs inside a page.
// Usage: node scripts/build-readability-source.mjs <path to Readability.js> <path to Readability-readerable.js>
import fs from 'node:fs';
const [, , main, readerable] = process.argv;
const body = fs.readFileSync(main, 'utf8').replace(/\r\n/g, '\n');
const ready = fs.readFileSync(readerable, 'utf8').replace(/\r\n/g, '\n');
const out = `// Generated by scripts/build-readability-source.mjs from Mozilla Readability (Apache-2.0, Copyright Mozilla). Do not edit.
// Source: https://github.com/mozilla/readability
export const READABILITY_SOURCE: string = ${JSON.stringify(body)};
export const READERABLE_SOURCE: string = ${JSON.stringify(ready)};
`;
fs.writeFileSync('src/browser-control/core/vendor/readability-source.ts', out);
console.log('written', out.length);
